#!/usr/bin/env python3
"""Build the controls library into the restricted, single-file native interface."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[1]
COMPONENTS = ROOT / 'components'
START = '<!-- BEGIN GENERATED AUDIO CONTROLS -->'
END = '<!-- END GENERATED AUDIO CONTROLS -->'


def replace_block(html, start, end, body, anchor):
    block = start + '\n' + body + '\n' + end
    if start in html:
        before, rest = html.split(start, 1)
        _, after = rest.split(end, 1)
        return before + block + after
    return html.replace(anchor, block + '\n' + anchor, 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    manifest = json.loads((COMPONENTS / 'library.json').read_text())
    styles = {'classicButtonCSS': 'classic.css', 'nativeButtonCSS': 'native.css', 'graphiteButtonCSS': 'graphite.css'}
    style_module = '// Generated by tools/sync-ui-controls.py; edit the CSS sources.\n' + ''.join(
        'export const ' + name + ' = ' + json.dumps((COMPONENTS / 'studio-button' / path).read_text()) + ';\n'
        for name, path in styles.items())
    outputs = {COMPONENTS / 'studio-button/styles.generated.js': style_module}
    sources = []
    for name in manifest['modules']:
        path = COMPONENTS / name
        source = outputs.get(path) if path in outputs else path.read_text()
        source = re.sub(r'^import .*?;\n', '', source, flags=re.M)
        source = re.sub(r'\bexport (class|const|function) ', r'\1 ', source)
        sources.append(source)
    target = ROOT / 'assets/interface.html'
    html = target.read_text()
    host_layout = html.split('<!-- BEGIN GENERATED STUDIO SKIN -->', 1)[0]
    obsolete = ['.sr-meter-led', '.sr-meter-channel', '.sr-vertical-scale', '.sr-gain-scale', '.sr-layer-gain::-webkit-slider-thumb']
    if any(selector in host_layout for selector in obsolete):
        raise SystemExit('Obsolete control implementation in host layout; edit components/ instead.')
    html = replace_block(html, START, END, '<script>\n' + '\n'.join(sources) + '</script>', '<script>')
    # Base geometry precedes application layout; material paint follows it.
    html = replace_block(html, '<!-- BEGIN GENERATED BUTTON BASE -->', '<!-- END GENERATED BUTTON BASE -->',
                         '<style>\n' + (COMPONENTS / manifest['styles'][0]).read_text() + '</style>', '<style>')
    skin = '\n'.join((COMPONENTS / name).read_text() for name in manifest['styles'][1:])
    html = replace_block(html, '<!-- BEGIN GENERATED STUDIO SKIN -->', '<!-- END GENERATED STUDIO SKIN -->',
                         '<style>\n' + skin + '</style>', START)
    outputs[target] = html
    stale = [str(path.relative_to(ROOT)) for path, body in outputs.items() if not path.exists() or path.read_text() != body]
    if args.check:
        if stale:
            raise SystemExit('Controls library is stale: ' + ', '.join(stale) + '. Run tools/sync-ui-controls.py.')
        print('Controls library, themes and embedded interface are in sync.')
    else:
        for path, body in outputs.items():
            if not path.exists() or path.read_text() != body:
                path.write_text(body)


if __name__ == '__main__':
    main()
